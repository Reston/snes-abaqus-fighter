def color15(rgb):
    r,g,b=rgb[:3]; return (r>>3)|((g>>3)<<5)|((b>>3)<<10)
def palbytes(colors): return b''.join(struct.pack('<H',color15(c)) for c in colors)
def tile(data,bpp=4):
    out=bytearray(8*bpp)
    for y in range(8):
        for x in range(8):
            c=data[y*8+x]
            for bit in range(bpp):
                out[(bit//2)*16+y*2+bit%2] |= ((c>>bit)&1) <<(7-x)
    return out
