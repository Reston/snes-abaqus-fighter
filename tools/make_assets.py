def brr(samples):
    data=bytearray()
    samples=samples+[0]*((-len(samples))%16)
    for i in range(0,len(samples),16):
        block=samples[i:i+16];peak=max(abs(v) for v in block)
        shift=max(0,min(12,math.ceil(math.log2(max(1,peak)/7))+1))
        scale=2**shift/2
        vals=[max(-8,min(7,round(v/scale)))&15 for v in block]
        data.append((shift<<4)|(1 if i+16==len(samples) else 0))
        data.extend((vals[k]<<4)|vals[k+1] for k in range(0,16,2))
    return data
