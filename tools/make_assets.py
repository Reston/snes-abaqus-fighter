def background(name,im):
    """Six local palettes, fifteen opaque colors per 8x8 tile, at most 896 tiles."""
    im=im.convert('RGB').resize((256,224),Image.Resampling.LANCZOS)
    tiles=[im.crop((x,y,x+8,y+8)) for y in range(0,224,8) for x in range(0,256,8)]
    means=[tuple(sum(p[k] for p in t.get_flattened_data())/64 for k in range(3)) for t in tiles]
    centers=[means[i] for i in (0,150,300,450,600,850)]
    groups=[]
    for _ in range(12):
        groups=[min(range(6),key=lambda j:sum((c[k]-centers[j][k])**2 for k in range(3))) for c in means]
        for j in range(6):
            points=[means[i] for i,g in enumerate(groups) if g==j]
            if points: centers[j]=tuple(sum(p[k] for p in points)/len(points) for k in range(3))
    pals=[];quantizers=[]
    for j in range(6):
        strips=[t for i,t in enumerate(tiles) if groups[i]==j] or [tiles[0]]
        canvas=Image.new('RGB',(8,len(strips)*8))
        for i,t in enumerate(strips):canvas.paste(t,(0,i*8))
        p=canvas.quantize(colors=15,method=Image.Quantize.MEDIANCUT).getpalette()[:45]
        palette=[(0,0,0)]+[tuple(p[k:k+3]) for k in range(0,45,3)]
        pals+=palette
        q=Image.new('P',(1,1));q.putpalette(sum((list(c) for c in palette[1:]),[])+list(p[-3:])*(256-15))
        quantizers.append(q)
    gfx=bytearray();tilemap=[];lookup={};preview=Image.new('RGB',(256,224))
    for i,t in enumerate(tiles):
        j=groups[i]
        q=t.quantize(palette=quantizers[j],dither=Image.Dither.NONE)
        indices=[min(v,14)+1 for v in q.get_flattened_data()]
        tb=bytes(tile(indices))
        if tb not in lookup:lookup[tb]=len(lookup);gfx+=tb
        tilemap.append(lookup[tb]|((j+2)<<10))
        out=Image.new('RGB',(8,8));out.putdata([pals[j*16+v] for v in indices]);preview.paste(out,((i%32)*8,(i//32)*8))
    tilemap += [0]*(1024-len(tilemap))
    assert len(gfx)<=0x7000
    asset(name+'_tiles',gfx);asset(name+'_map',struct.pack('<1024H',*tilemap));asset(name+'_pal',palbytes(pals))
    preview.save(OUT/(name+'.png'))
    return preview

